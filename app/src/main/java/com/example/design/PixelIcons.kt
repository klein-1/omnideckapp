@Composable
fun PixelGlyph(
    glyphKey: String,
    accentColor: Color,
    modifier: Modifier = Modifier,
    scale: Int = 2,
    fallbackMonogram: String = "DK"
) {
    val look = LocalDotkitLook.current
    val ink = look.palette.ink
    val rows = PixelIconCatalog.GLYPHS[glyphKey]
    val sizeDp = (16 * scale.coerceIn(1, 4)).dp

    if (rows == null) {
        Box(
            modifier = modifier
                .size(sizeDp)
                .background(accentColor)
                .border(2.dp, ink),
            contentAlignment = Alignment.Center
        ) {
            Text(
                text = fallbackMonogram.take(2).uppercase(),
                style = DotkitType.displayPixel(if (scale >= 2) 14 else 10),
                color = ink
            )
        }
        return
    }

    Canvas(modifier = modifier.size(sizeDp)) {
        val cellW = size.width / 16f
        val cellH = size.height / 16f
        for (r in 0 until minOf(16, rows.size)) {
            val rowStr = rows[r]
            for (c in 0 until minOf(16, rowStr.length)) {
                val ch = rowStr[c]
                if (ch == '#' || ch == '+') {
                    drawRect(
                        color = if (ch == '#') ink else accentColor,
                        topLeft = Offset(c * cellW, r * cellH),
                        size = Size(cellW + 0.4f, cellH + 0.4f)
                    )
                }
            }
        }
    }
}

enum class SpecimenSceneKind { RULER, STAMP, CASSETTE, LOUPE, DIAL, FLOPPY }

@Composable
fun PixelSceneIllustration(
    kind: SpecimenSceneKind,
    accentColor: Color,
    modifier: Modifier = Modifier
) {
    val palette = LocalDotkitLook.current.palette
    Canvas(
        modifier = modifier
            .size(64.dp)
            .background(palette.paper3)
            .border(2.dp, palette.ink)
    ) {
        val u = size.width / 16f
        // Registration corner marks
        drawRect(palette.ink, Offset(u, u), Size(2 * u, u))
        drawRect(palette.ink, Offset(u, u), Size(u, 2 * u))
        drawRect(palette.ink, Offset(13 * u, 14 * u), Size(2 * u, u))
        drawRect(palette.ink, Offset(14 * u, 13 * u), Size(u, 2 * u))

        when (kind) {
            SpecimenSceneKind.STAMP -> {
                drawRect(accentColor, Offset(4 * u, 3 * u), Size(8 * u, 4 * u))
                drawRect(palette.ink, Offset(6 * u, 7 * u), Size(4 * u, 3 * u))
                drawRect(palette.ink, Offset(3 * u, 10 * u), Size(10 * u, 3 * u))
            }
            SpecimenSceneKind.RULER -> {
                drawRect(accentColor, Offset(2 * u, 6 * u), Size(12 * u, 5 * u))
                for (i in 3..13 step 2) {
                    drawRect(palette.ink, Offset(i * u, 6 * u), Size(u, 2.5f * u))
                }
            }
            SpecimenSceneKind.CASSETTE -> {
                drawRect(palette.ink, Offset(2 * u, 4 * u), Size(12 * u, 8 * u))
                drawRect(accentColor, Offset(3 * u, 5 * u), Size(10 * u, 4 * u))
                drawRect(palette.paper, Offset(4 * u, 6 * u), Size(2 * u, 2 * u))
                drawRect(palette.paper, Offset(10 * u, 6 * u), Size(2 * u, 2 * u))
            }
            SpecimenSceneKind.LOUPE -> {
                drawRect(accentColor, Offset(4 * u, 3 * u), Size(6 * u, 6 * u))
                drawRect(palette.paper, Offset(5 * u, 4 * u), Size(4 * u, 4 * u))
                drawRect(palette.ink, Offset(9 * u, 9 * u), Size(4 * u, 4 * u))
            }
            SpecimenSceneKind.DIAL -> {
                drawRect(palette.ink, Offset(3 * u, 3 * u), Size(10 * u, 10 * u))
                drawRect(accentColor, Offset(4 * u, 4 * u), Size(8 * u, 8 * u))
                drawRect(palette.ink, Offset(7 * u, 5 * u), Size(2 * u, 4 * u))
            }
            SpecimenSceneKind.FLOPPY -> {
                drawRect(palette.ink, Offset(3 * u, 2 * u), Size(10 * u, 12 * u))
                drawRect(accentColor, Offset(5 * u, 2 * u), Size(6 * u, 4 * u))
                drawRect(palette.paper, Offset(4 * u, 8 * u), Size(8 * u, 5 * u))
            }
        }
    }
}
